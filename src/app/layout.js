import { Josefin_Sans, Caveat } from "next/font/google";
import "./globals.css";
import { Navbar } from "@/components/navbar/navbar";
import { Footer } from "@/components/footer/footer";
import { getDestinations } from "@/lib/destinations-server";

const josefinSans = Josefin_Sans({

  subsets: ["latin"],
});

const caveat = Caveat({
  subsets: ["latin"],
  variable: "--font-hand",
});


export const metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }) {
  /* One cached fetch shared by the footer gallery on every page */
  const destinations = await getDestinations();

  return (
    <html
      lang="en"
      suppressHydrationWarning
      className={`${josefinSans.className} ${caveat.variable} scroll-smooth h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        {/* Apply saved theme before first paint to avoid a flash */}
        <script
          dangerouslySetInnerHTML={{
            __html: "try{if(localStorage.getItem('theme')==='dark')document.documentElement.classList.add('dark')}catch(e){}",
          }}
        />
              <Navbar />

        {children}
         <Footer destinations={destinations} />
        </body>
    </html>
  );
}
